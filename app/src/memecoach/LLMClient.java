package memecoach;

/**
 * LLM client interface.
 * Function: Defines how Meme Coach requests explanations from the large language model.
 * The current interface does not make HTTP requests itself, nor does it store any APIKey.
 * In the future, specific clients will implement this interface,
 and send the requests to our own backend server.
 In this way, the LLMFeedbackService does not need to know:
 1. Which AI model to use
 2. Where the backend server is deployed
 3. How the network requests are actually implemented
 This reflects the Dependency Inversion Principle.
 */

public interface LLMClient {

    /**
     * Please have the AI generate the knowledge explanation for the Quiz.
     *
     * @param systemPrompt The role and response style of the AI
     * @param userPrompt The quiz questions, user answers, and correct answers
     * @return The explanation text generated by the AI
     * @throws Exception An exception is thrown when the network or API request fails
     */
    String requestExplanation(
            String systemPrompt,
            String userPrompt
    ) throws Exception;
}

